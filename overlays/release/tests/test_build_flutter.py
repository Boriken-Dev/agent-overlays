def test_sync_copies_what_the_lock_names_without_what_a_build_never_reads(build, app, capsys):
    root, cache, deps = app
    assert sync(build, root, cache, deps) == 0
    assert "pub: 2 hosted packages, 1 git checkouts" in capsys.readouterr().out
    pub = tree_of(deps / "pub")

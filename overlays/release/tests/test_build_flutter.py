def test_sync_copies_what_the_lock_names_without_what_a_build_never_reads(build, app, capsys):
    root, cache, deps = app
    assert sync(build, root, cache, deps) == 0
    assert "pub: 2 hosted packages, 1 git checkouts" in capsys.readouterr().out
    pub = tree_of(deps / "pub")
    assert "hosted/pub.dev/async-2.11.0/lib/async.dart" in pub
    assert "hosted/pub.dev/async-2.11.0/pubspec.yaml" in pub
    assert not any("/test/" in p or "/doc/" in p or "/.github/" in p for p in pub)
    assert "hosted/pub.dev/async-2.11.0/lib/native.bin" not in pub, "a refused file is deleted"
    assert "hosted-hashes/pub.dev/async-2.11.0.sha256" in pub
    assert "hosted/pub.dev/.cache/async-versions.json" in pub
    assert not any("unrelated" in p for p in pub), "a package the lock does not name is not copied"
    assert f"git/{GIT_KEY}/pkg/inner/pubspec.yaml" in pub
    assert not any("/.git/" in p for p in pub), "no .git below a pub git checkout"
    assert not any("gitpkg-bare" in p for p in pub)


def test_the_manifest_lists_the_packages_the_drops_and_the_deleted_files(build, app):
    root, cache, deps = app
    sync(build, root, cache, deps)
    pub = json.loads((deps / "manifest.json").read_text())["pub"]
    assert pub["packages"] == ["async-2.11.0", "tray_manager-0.5.0"]
    assert pub["dropped"]["directories"] == ["test", "tests", "example", "examples", "benchmark", "benchmarks", "doc", "docs", ".github"]
    assert pub["dropped"]["deletedFlaggedFiles"] == [{"path": "pub/hosted/pub.dev/async-2.11.0/lib/native.bin", "kind": "elf executable"}]
    assert pub["dropped"]["counts"]["elf executable"] == 1 and pub["dropped"]["counts"]["test"] == 2
    assert pub["gitDependencies"] == [
        {"package": "gitpkg", "url": "https://example.test/org/gitpkg.git", "path": "pkg/inner", "ref": "1" * 40, "mode": "checkout"}
    ]
    assert pub["require"] == ["tray_manager"] and pub["systemPackages"] == ["libgtk-3-dev"]


def test_a_second_sync_changes_nothing_and_a_package_leaving_the_lock_is_removed(build, app, capsys):
    root, cache, deps = app
    sync(build, root, cache, deps)
    before = tree_of(deps)
    capsys.readouterr()
    sync(build, root, cache, deps)
    assert tree_of(deps) == before
    without = lambda name: re.sub(rf"  {name}:\n(?:    .*\n|      .*\n)+", "", PUBSPEC, count=1)  # noqa: E731
    (root / "app" / "pubspec.lock").write_text(without("async"), encoding="utf-8")
    assert sync(build, root, cache, deps) == 0
    pub = tree_of(deps / "pub")
    assert not any("async" in p for p in pub), "a package the lock stopped naming is removed with its hash"
    assert any("tray_manager-0.5.0" in p for p in pub)
    (root / "app" / "pubspec.lock").write_text(without("tray_manager"), encoding="utf-8")
    capsys.readouterr()
    assert sync(build, root, cache, deps) == 1, "the require list now fails"
    assert "required packages missing from pubspec.lock: tray_manager" in capsys.readouterr().err



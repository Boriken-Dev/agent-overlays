LOCK = f"""# lock
app flutter {'a' * 40} any - https://github.com/flutter/flutter.git
app flutter-version 3.50.0-1.0.pre-230 any - -
app flutter-engine {'b' * 40} any - -
app dart 3.15.0-72.0.dev any - -
"""


@pytest.fixture
def flutter_root(build, tmp_path):
    root = tmp_path / "repo"
    ctx_for(build, root)
    (root / "tools" / "sdk.lock").write_text(LOCK, encoding="utf-8")
    sdk = tmp_path / "flutter"
    (sdk / "bin" / "cache").mkdir(parents=True)
    (sdk / "bin" / "cache" / "flutter.version.json").write_text(
        '{\n  "frameworkVersion": "3.50.0-1.0.pre-230",\n  "dartSdkVersion": "3.15.0 (build 3.15.0-72.0.dev)"\n}\n', encoding="utf-8"
    )
    (sdk / "bin" / "cache" / "engine.stamp").write_text("b" * 40 + "\n", encoding="utf-8")
    return root, sdk


def test_precache_check_passes_when_flutter_reports_what_the_lock_names(build, flutter_root, capsys):
    root, sdk = flutter_root
    assert build.main(["--root", str(root), "flutter", "precache-check", "--flutter-root", str(sdk)]) == 0
    assert "ok: Flutter 3.50.0-1.0.pre-230" in capsys.readouterr().out


def test_precache_check_names_each_difference(build, flutter_root, capsys):
    root, sdk = flutter_root
    (sdk / "bin" / "cache" / "engine.stamp").write_text("c" * 40, encoding="utf-8")
    (sdk / "bin" / "cache" / "flutter.version.json").write_text('{"frameworkVersion": "3.49.0", "dartSdkVersion": "3.14.0"}', encoding="utf-8")
    assert build.main(["--root", str(root), "flutter", "precache-check", "--flutter-root", str(sdk)]) == 1
    err = capsys.readouterr().err
    assert "flutter reports version 3.49.0, the lock says 3.50.0-1.0.pre-230" in err
    assert f"flutter's engine is {'c' * 40}" in err and "flutter's Dart is 3.14.0" in err


def test_precache_check_needs_a_precached_checkout_and_a_root(build, flutter_root, tmp_path, monkeypatch, capsys):
    root, sdk = flutter_root
    (sdk / "bin" / "cache" / "engine.stamp").unlink()
    assert build.main(["--root", str(root), "flutter", "precache-check", "--flutter-root", str(sdk)]) == 1
    assert "run `flutter precache`" in capsys.readouterr().err
    monkeypatch.delenv("FLUTTER_ROOT", raising=False)
    with pytest.raises(SystemExit) as stop:
        build.main(["--root", str(root), "flutter", "precache-check"])
    assert stop.value.code == 2
    monkeypatch.setenv("FLUTTER_ROOT", str(sdk))
    assert build.main(["--root", str(root), "flutter", "precache-check"]) == 1



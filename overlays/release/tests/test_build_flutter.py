    (deps / "pub" / "hosted-hashes" / "pub.dev" / "async-2.11.0.sha256").write_text("aaaa", encoding="utf-8")
    import shutil

    shutil.rmtree(deps / "pub" / "hosted" / "pub.dev" / "tray_manager-0.5.0")
    code, result = plan(build, root, deps, cache, capsys)
    assert code == 1 and "lacks hosted packages: tray_manager-0.5.0" in result["reason"]



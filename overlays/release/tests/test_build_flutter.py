def test_the_pubspec_lock_is_read_by_indentation(build):
    packages = {p.name: p for p in build.parse_pubspec_lock(PUBSPEC)}
    assert set(packages) == {"async", "tray_manager", "flutter", "local_thing", "gitpkg"}
    async_ = packages["async"]
    assert (async_.source, async_.version, async_.sha256, async_.url, async_.host, async_.key) == (
        "hosted", "2.11.0", "aaaa", "https://pub.dev", "pub.dev", "async-2.11.0"
    )
    git = packages["gitpkg"]
    assert (git.source, git.path, git.resolved_ref, git.repo, git.key) == ("git", "pkg/inner", "1" * 40, "gitpkg", GIT_KEY)
    assert packages["flutter"].source == "sdk" and packages["local_thing"].source == "path"



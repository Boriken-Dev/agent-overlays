GIT_KEY = "gitpkg-1111111111111111111111111111111111111111"


def make_cache(root: Path) -> Path:
    """A user pub cache holding what PUBSPEC names, with things a build never reads."""
    hosted = root / "hosted" / "pub.dev"
    for name, version in (("async", "2.11.0"), ("tray_manager", "0.5.0")):
        package = hosted / f"{name}-{version}"
        (package / "lib").mkdir(parents=True)
        (package / "lib" / f"{name}.dart").write_text("void f() {}\n", encoding="utf-8")
        (package / "pubspec.yaml").write_text(f"name: {name}\n", encoding="utf-8")
        (package / "test").mkdir()
        (package / "test" / "t.dart").write_text("x", encoding="utf-8")
        (package / "doc").mkdir()
        (package / "doc" / "a.md").write_text("x", encoding="utf-8")
        (package / ".github").mkdir()
        (package / ".github" / "ci.yml").write_text("x", encoding="utf-8")
    (hosted / "async-2.11.0" / "lib" / "native.bin").write_bytes(FLAGGED["elf executable"])
    (hosted / ".cache").mkdir()
    (hosted / ".cache" / "async-versions.json").write_text("{}", encoding="utf-8")
    (root / "hosted-hashes" / "pub.dev").mkdir(parents=True)
    (root / "hosted-hashes" / "pub.dev" / "async-2.11.0.sha256").write_text("aaaa", encoding="utf-8")
    (root / "hosted-hashes" / "pub.dev" / "tray_manager-0.5.0.sha256").write_text("bbbb", encoding="utf-8")
    (root / "hosted-hashes" / "pub.dev" / "unrelated-1.0.0.sha256").write_text("cccc", encoding="utf-8")
    (hosted / "unrelated-1.0.0").mkdir()
    checkout = root / "git" / GIT_KEY
    (checkout / "pkg" / "inner").mkdir(parents=True)
    (checkout / "pkg" / "inner" / "pubspec.yaml").write_text("name: gitpkg\n", encoding="utf-8")
    (checkout / ".git").mkdir()
    (checkout / ".git" / "HEAD").write_text("ref", encoding="utf-8")
    (root / "git" / "cache" / "gitpkg-bare").mkdir(parents=True)
    return root


@pytest.fixture
def app(build, tmp_path):
    """A repository with an empty Cargo.lock, a pubspec.lock and a user pub cache."""
    root = init_repo(tmp_path / "repo")
    ctx_for(build, root, CFG)
    (root / "Cargo.lock").write_text("version = 4\n", encoding="utf-8")
    (root / "app").mkdir()
    (root / "app" / "pubspec.lock").write_text(PUBSPEC, encoding="utf-8")
    commit_all(root)
    return root, make_cache(tmp_path / "cache"), tmp_path / "deps"


def sync(build, root, cache, deps, *extra):
    return build.main(["--root", str(root), "deps", "sync", "--deps", str(deps), "--pub-cache", str(cache), *extra])


def tree_of(base: Path) -> set[str]:
    return {p.relative_to(base).as_posix() for p in base.rglob("*") if p.is_file()}



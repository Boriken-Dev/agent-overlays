    assert sync(build, root, cache, deps) == 0
    assert (deps / "cdn" / "fonts.gstatic.com" / "s" / "roboto.ttf").read_bytes() == files["/s/roboto.ttf"]
    assert sorted(asked) == ["https://fonts.gstatic.com/s/roboto.ttf", "https://www.gstatic.com/flutter-canvaskit/abc/canvaskit.wasm"]
    listed = json.loads((deps / "manifest.json").read_text())["cdn"]["files"]
    assert [f["path"] for f in listed] == ["/s/roboto.ttf", "/flutter-canvaskit/abc/canvaskit.wasm"], "sorted by host, then path"
    asked.clear()
    sync(build, root, cache, deps)
    assert asked == [], "a file that is there with the right hash is not fetched again"



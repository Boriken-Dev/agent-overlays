def plan(build, root, deps, cache, capsys, *extra):
    code = build.main(["--root", str(root), "offline", "plan", "--json", "--deps", str(deps), "--pub-cache", str(cache), *extra])
    return code, json.loads(capsys.readouterr().out)


def test_offline_plan_seeds_the_cache_and_writes_the_cargo_home(build, app, tmp_path, capsys):
    root, cache, deps = app
    sync(build, root, cache, deps)
    capsys.readouterr()
    code, result = plan(build, root, deps, cache, capsys, "--out", str(tmp_path / "home"))
    assert code == 0 and result["reason"] is None
    target = Path(result["cache"])
    assert target == root / "target" / "offline-pub-cache"
    assert (target / "hosted" / "pub.dev" / "async-2.11.0" / "pubspec.yaml").is_file()
    assert (target / "hosted-hashes" / "pub.dev" / "async-2.11.0.sha256").is_file()
    assert (target / "git" / GIT_KEY / ".git" / "pub-packages").is_file(), "pub reads a checkout once it has .git/pub-packages"
    assert Path(result["cargo_home"]) == (tmp_path / "home" / "cargo-home").resolve()
    assert not (target / "hosted" / "pub.dev" / "unrelated-1.0.0").exists()


